// 生成 src/styles/fonts.css：Noto Serif SC（OFL）400/500 的 unicode-range 分片，仅 woff2。
// 浏览器只下载页面实际用到的字符分片（CJK 子集化）。重新生成：node scripts/gen-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';
let out = '/* generated by scripts/gen-fonts.mjs — Noto Serif SC (SIL OFL 1.1), woff2 unicode-range subsets */\n';
for (const w of [400, 500]) {
  const css = readFileSync(`node_modules/@fontsource/noto-serif-sc/${w}.css`, 'utf8');
  out += css
    .replace(/url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\), url\([^)]+\.woff\) format\('woff'\)/g,
      "url('../../node_modules/@fontsource/noto-serif-sc/files/$1') format('woff2')")
    .replace(/\/\*.*?\*\/\n/g, '');
}
writeFileSync('src/styles/fonts.css', out);
console.log('ok', (out.match(/@font-face/g) || []).length, 'faces');
